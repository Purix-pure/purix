// packages/core/src/test-support/real_node_modules.ts
//
// Several test files symlink this project's own node_modules into a fresh
// temp dir so a real `tsc` (or other pinned local binary) can be found
// there, instead of falling through to an un-pinned global/npx resolution
// (resolveRealNodeModules — see verify.test.ts, drift.test.ts,
// migration.test.ts). Others need to spawn this monorepo's own pinned
// `tsx` as a real, separate OS process (resolveTsxCommand — see
// config_hot_reload.test.ts, scheduler.test.ts, providers.test.ts,
// budget_worktree.test.ts).
//
// Where that real node_modules actually lives depends on the package
// manager that installed it:
//   - pnpm (and yarn without hoisting) create a node_modules directory
//     local to each workspace package (packages/core/node_modules),
//     containing symlinks into the shared store.
//   - npm workspaces hoist everything to the monorepo root by default —
//     packages/core/node_modules doesn't exist at all in that case, and
//     dependencies live in the repo root's node_modules instead.
//
// Hardcoding either path breaks tests under the other package manager
// (the actual bug this file fixes — npm hoisting left the local
// node_modules missing and these tests fell through to a "not_installed"
// state instead of testing real tsc behavior). Walk up from this
// package's own directory and use the first node_modules that actually
// contains a resolvable `typescript` install.
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

/**
 * Finds a node_modules directory containing the given package name,
 * starting at packages/core and walking up toward the filesystem root.
 * Returns null if none is found — callers should treat that the same as
 * "not installed" and degrade gracefully, same as before this helper
 * existed.
 */
export function resolveRealNodeModules(pkgName: string = "typescript"): string | null {
  let dir = resolve(import.meta.dirname, "..", "..");
  // eslint-disable-next-line no-constant-condition
  while (true) {
    const candidate = join(dir, "node_modules");
    if (existsSync(join(candidate, pkgName))) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return null; // reached filesystem root
    dir = parent;
  }
}

/**
 * Builds the command array to invoke this monorepo's own pinned `tsx`
 * directly (no npx, no PATH lookup — several tests rely on spawning a
 * REAL separate OS process quickly and deterministically). Several test
 * files used to hardcode `packages/core/../../node_modules/...`, which
 * only exists under pnpm's non-hoisted layout; under npm's hoisted
 * layout that directory doesn't exist and every one of those spawns
 * failed with ENOENT. Resolve the real node_modules the same
 * package-manager-agnostic way resolveRealNodeModules() does, then point
 * at tsx inside whichever directory that turns out to be.
 */
export function resolveTsxCommand(): string[] {
  const nodeModules = resolveRealNodeModules("tsx");
  if (!nodeModules) {
    // Fall back to a network/PATH-dependent resolution rather than
    // crashing outright — same "best effort" spirit as the rest of
    // these test helpers.
    return ["npx", "tsx"];
  }
  return process.platform === "win32"
    ? [process.execPath, join(nodeModules, "tsx", "dist", "cli.mjs")]
    : [join(nodeModules, ".bin", "tsx")];
}