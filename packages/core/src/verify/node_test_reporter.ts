// src/verify/node_test_reporter.ts
//
// Structured results from `node --test`, without reading its console text.
// NODE_SUPPORT_POLICY.md: "Do not parse test-runner text output ... use the events a custom
// reporter receives." The old code parsed `--test-reporter=tap`, and broke when Node 22.13.0
// (this project's engines floor) stopped writing `type:` for leaf tests: no regex over that text
// can be both permissive and correct. A custom reporter receives the runner's own events.
//
// The reporter below is written next to the project's tmp data (.purix/tmp) and passed as
// `--test-reporter=<file>`. It emits one line per finished test: PURIX_TEST <json>. Reading those
// lines is reading Purix's own protocol, not Node's presentation format.
//
// Leaf detection does not rely on `details.type`, which not every Node version sets: a test is a
// suite if it announced itself as one OR if any test started inside it. A suite that failed with
// no failing child is reported as a failure (its own hook or assertion failed), never swallowed.
import { existsSync, readFileSync } from "node:fs";
import { writeFileAtomic } from "../platform/atomic_write.js";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { purixTmpRoot } from "../platform/layout.js";

export const REPORTER_LINE_PREFIX = "PURIX_TEST ";
const REPORTER_FILENAME = "purix-node-reporter.mjs";

const REPORTER_SOURCE = `// Generated by Purix (verify/node_test_reporter.ts). Safe to delete.
export default async function* purixReporter(source) {
  const stack = [];
  for await (const ev of source) {
    if (ev.type === "test:start") {
      const parent = stack[stack.length - 1];
      if (parent) parent.hasChild = true;
      stack.push({ nesting: ev.data.nesting, hasChild: false, childFailed: false });
    } else if (ev.type === "test:pass" || ev.type === "test:fail") {
      let frame = null;
      while (stack.length > 0) {
        const top = stack.pop();
        if (top.nesting === ev.data.nesting) { frame = top; break; }
      }
      const passed = ev.type === "test:pass";
      const isSuite = (ev.data.details && ev.data.details.type === "suite") || (frame !== null && frame.hasChild);
      if (!passed && stack.length > 0) stack[stack.length - 1].childFailed = true;
      if (isSuite && (passed || (frame && frame.childFailed))) continue; // rollup of children: not a result of its own
      // A file that declares no test is reported by node as ONE passing "test" named after the file (its path as given, or its basename). That is not a test, and
      // counting it made an empty file read as a pass (A6-1). A crash at load is a test:fail and is kept. If a real test shares
      // its file's name it is dropped too, which can only make a pass read as a run that exercised nothing, never the other way round.
      const fileName = typeof ev.data.file === "string" ? ev.data.file.replace(/\\\\/g, "/") : null;
      const testName = typeof ev.data.name === "string" ? ev.data.name.replace(/\\\\/g, "/") : null;
      if (passed && ev.data.nesting === 0 && fileName !== null && testName !== null && (testName === fileName || fileName.endsWith("/" + testName)) && !(frame && frame.hasChild)) continue;
      // skip and todo: the test did not (or need not) run. Not a pass, not a failure (A6-1 count rule).
      const skipped = (ev.data.skip !== undefined && ev.data.skip !== false) || (ev.data.todo !== undefined && ev.data.todo !== false);
      yield ${JSON.stringify(REPORTER_LINE_PREFIX)} + JSON.stringify({ name: ev.data.name, passed, skipped, file: ev.data.file ?? null }) + "\\n";
    }
  }
}
`;

/** Writes (or refreshes) the reporter under baseDir/.purix/tmp and returns its absolute path. */
export function ensureNodeTestReporter(baseDir: string): string {
  const path = join(purixTmpRoot(baseDir), REPORTER_FILENAME);
  if (!existsSync(path) || readFileSync(path, "utf-8") !== REPORTER_SOURCE) writeFileAtomic(path, REPORTER_SOURCE);
  return path;
}

/**
 * The value for `--test-reporter=`. Node loads a custom reporter through its ES-module loader, which treats the value as a
 * module specifier. On Windows an absolute path such as C:\\Users\\me\\p\\reporter.mjs is not a valid specifier (the loader
 * reads "C:" as a URL scheme and throws ERR_UNSUPPORTED_ESM_URL_SCHEME: "On Windows, absolute paths must be valid file://
 * URLs"), so the test run died before any test started and Purix recorded a bare failure. A file:// URL is valid on every OS
 * and survives spaces and non-ASCII characters in the path.
 */
export function reporterSpecifier(reporterPath: string): string {
  return pathToFileURL(reporterPath).href;
}

export interface ReportedTest { name: string; passed: boolean; skipped?: boolean; file: string | null }

export function parseReporterOutput(stdout: string): ReportedTest[] {
  const out: ReportedTest[] = [];
  for (const line of stdout.split("\n")) {
    if (!line.startsWith(REPORTER_LINE_PREFIX)) continue;
    try {
      const o = JSON.parse(line.slice(REPORTER_LINE_PREFIX.length));
      if (typeof o?.name === "string" && typeof o?.passed === "boolean") out.push({ name: o.name, passed: o.passed, ...(o.skipped === true ? { skipped: true } : {}), file: typeof o.file === "string" ? o.file : null });
    } catch { /* a partial line from a killed run: ignore it, the exit code still decides */ }
  }
  return out;
}
